import { describe, expect, it } from "vitest";
import { BUG_DEFAULTS, type Gathered, type Section } from "../../src/bug/gather";
import {
  BUG_REPO,
  newIssueUrl,
  renderReport,
  summaryBody,
  titleOf,
  trimToLimit,
} from "../../src/bug/report";

const gathered = (sections: Section[], over: Partial<Gathered> = {}): Gathered => ({
  header:
    "volley 0.13.2 · installer (v0.13.2) · Ubuntu 24.04 x64 · bun 1.3.2 · layout linux-apt · network none · this machine: supervisor",
  sections,
  wave: "wave-a",
  version: "0.13.2",
  firstFailure: null,
  failures: [],
  ghSignedIn: false,
  identity: { ghLogin: null, gitNames: [], repos: [], hosts: [] },
  ...over,
});
const lines = (n: number, w: number, tag: string) =>
  Array.from({ length: n }, (_, i) => `${tag} ${i} ${"x".repeat(w)}`).join("\n");

describe("titleOf", () => {
  it("the message's first line, else the first failure, else the version", () => {
    expect(
      titleOf({ message: "first wave never started\nmore", firstFailure: "x", version: "0.13.2" }),
    ).toBe("bug: first wave never started");
    expect(
      titleOf({ message: "", firstFailure: "setup step broker blocked", version: "0.13.2" }),
    ).toBe("bug: setup step broker blocked");
    expect(titleOf({ firstFailure: null, version: "0.13.2" })).toBe(
      "bug: report from volley 0.13.2",
    );
  });
});

describe("renderReport", () => {
  it("the message, the header, a fenced block per section, the footer", () => {
    const text = renderReport(
      gathered([{ id: "tools", title: "Tools", kind: "info", body: "bun: 1.3.2" }]),
      { message: "it broke", keepRepos: false },
    );
    expect(text).toContain("## What happened\n\nit broke");
    expect(text).toContain("volley 0.13.2 · installer (v0.13.2)");
    expect(text).toContain("### Tools\n\n```\nbun: 1.3.2\n```");
    expect(text.trimEnd().split("\n").at(-1)).toBe(
      "generated by volley bug 0.13.2; redacted: tokens, e-mails, user, host, ips, repos",
    );
    expect(renderReport(gathered([]), { keepRepos: true })).toContain(
      "redacted: tokens, e-mails, user, host, ips\n",
    );
  });
});

describe("trimToLimit", () => {
  const big = () =>
    gathered([
      { id: "tools", title: "Tools", kind: "info", body: "bun: 1.3.2" },
      { id: "journal", title: "Journal", kind: "journal", body: lines(40, 400, "event") },
      { id: "log-volleyd", title: "volleyd.log", kind: "log", body: lines(80, 400, "log") },
      { id: "log-desk", title: "desk.log", kind: "log", body: lines(80, 400, "desk") },
    ]);
  const render = (g: Gathered) => renderReport(g, { keepRepos: false });

  it("drops log lines first, oldest first, and says so", () => {
    const g = big();
    const text = trimToLimit(g, render, BUG_DEFAULTS.body_max);
    expect(text.length).toBeLessThanOrEqual(BUG_DEFAULTS.body_max);
    expect(text).toMatch(/… \d+ log lines dropped/);
    expect(text).toContain("event 0 ");
    expect(text).toContain(g.header);
    expect(text).toContain("log 79 ");
    expect(text).not.toContain("log 0 x");
  });

  it("then the journal, never the header", () => {
    const text = trimToLimit(big(), render, 8_000);
    expect(text.length).toBeLessThanOrEqual(8_000);
    expect(text).toMatch(/… \d+ journal events dropped/);
    expect(text).toContain(big().header);
    expect(text).toContain("bun: 1.3.2");
  });

  it("a report within the limit is left as it is", () => {
    const g = gathered([{ id: "tools", title: "Tools", kind: "info", body: "bun: 1.3.2" }]);
    expect(trimToLimit(g, render, BUG_DEFAULTS.body_max)).toBe(render(g));
  });
});

describe("the browser page", () => {
  const file = "volley-bug-20261025-120000.md";
  it("summaryBody: the header, the first failing rows, then the paste instruction", () => {
    const body = summaryBody("volley 0.13.2 · clone", ["setup step broker blocked"], file);
    expect(body).toContain("volley 0.13.2 · clone");
    expect(body).toContain("- setup step broker blocked");
    expect(body.trimEnd().endsWith(`paste the contents of ${file} below`)).toBe(true);
  });

  it("newIssueUrl: the bug form, at most 6 000 characters whatever the size", () => {
    for (const n of [0, 5, 500]) {
      const url = newIssueUrl({
        title: `bug: ${"t".repeat(n)}`,
        message: "m".repeat(n * 10),
        header: "volley 0.13.2 · clone",
        failures: Array.from(
          { length: n },
          (_, i) => `doctor check c${i} failing ${"z".repeat(50)}`,
        ),
        file,
      });
      expect(url.length).toBeLessThanOrEqual(BUG_DEFAULTS.url_max);
      expect(url.startsWith(`https://github.com/${BUG_REPO}/issues/new?`)).toBe(true);
      const q = new URL(url).searchParams;
      expect(q.get("template")).toBe("bug.yml");
      expect(q.get("title")?.startsWith("bug: ")).toBe(true);
      expect(q.get("report")?.trimEnd().endsWith(`paste the contents of ${file} below`)).toBe(true);
    }
    expect(BUG_REPO).toBe("kryptek/volley");
  });
});
