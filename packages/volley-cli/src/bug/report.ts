import { BUG_DEFAULTS, type Gathered, type Section } from "./gather";
import { redactedList } from "./redact";

/**
 * `volley bug`'s report: Markdown, the person's words first, then the header line and one fenced
 * block per section, ending with a footer that says what the redaction replaced. Trimmed to
 * GitHub's body limit from the logs first, then the journal, never the header. The browser
 * transport's page carries a summary only (GitHub refuses long URLs), the full report saved beside
 * the person.
 */

/** Where reports go. */
export const BUG_REPO = "kryptek/volley";

/** The issue form's field ids (`.github/ISSUE_TEMPLATE/bug.yml`). */
export const FORM = { template: "bug.yml", whatHappened: "what-happened", report: "report" };

export interface RenderOptions {
  message?: string;
  keepRepos: boolean;
}

const firstLine = (s: string | undefined) => (s ?? "").trim().split("\n")[0]?.trim() ?? "";

/** `bug: <the message's first line>`, else the first failure, else the version. */
export function titleOf(o: { message?: string; firstFailure: string | null; version: string }) {
  const why = firstLine(o.message) || o.firstFailure || `report from volley ${o.version}`;
  return `bug: ${why.length > 100 ? `${why.slice(0, 99)}…` : why}`;
}

function fence(s: Section): string {
  const ticks = "`".repeat(
    Math.max(3, ...[...s.body.matchAll(/`{3,}/g)].map((m) => m[0].length + 1)),
  );
  return `### ${s.title}\n\n${ticks}${s.lang ?? ""}\n${s.body}\n${ticks}\n`;
}

export function renderReport(g: Gathered, opts: RenderOptions): string {
  const message = (opts.message ?? "").trim();
  return [
    "## What happened\n",
    `${message !== "" ? message : "_(say what you ran, what happened and what you expected)_"}\n`,
    "## Diagnostics\n",
    `\`${g.header}\`\n`,
    ...g.sections.map(fence),
    "---\n",
    `generated by volley bug ${g.version}; redacted: ${redactedList(opts).join(", ")}\n`,
  ].join("\n");
}

/**
 * `render(g)` at most `max` characters: log lines dropped first (oldest first, each section
 * saying how many), then journal events, never the header. A report still too long after both
 * is cut, and says so.
 */
export function trimToLimit(g: Gathered, render: (g: Gathered) => string, max: number): string {
  let text = render(g);
  if (text.length <= max) return text;
  const sections = g.sections.map((s) => ({ ...s }));
  const trimmed: Gathered = { ...g, sections };
  for (const [kind, noun] of [
    ["log", "log lines"],
    ["journal", "journal events"],
  ] as const) {
    const of = sections.filter((s) => s.kind === kind);
    const lines = new Map(of.map((s) => [s, s.body.split("\n")]));
    // `k` rounds of one line per section, oldest first, so every section keeps its newest lines.
    const drop = (k: number) => {
      for (const [s, ls] of lines) {
        const n = Math.min(k, ls.length);
        if (n > 0) s.body = [`… ${n} ${noun} dropped`, ...ls.slice(n)].join("\n");
        else s.body = ls.join("\n");
      }
      return render(trimmed);
    };
    // The fewest rounds that fit, found by bisection: each render redacts the whole report.
    const most = Math.max(0, ...[...lines.values()].map((ls) => ls.length));
    let lo = 0;
    let hi = most;
    while (lo < hi) {
      const mid = (lo + hi) >> 1;
      if (drop(mid).length <= max) hi = mid;
      else lo = mid + 1;
    }
    text = drop(lo);
    if (text.length <= max) return text;
  }
  const note = "\n… the report was cut here: it was longer than GitHub takes\n";
  return `${text.slice(0, max - note.length)}${note}`;
}

/** The browser page's report field: the header, the first failing rows, the paste instruction. */
export function summaryBody(header: string, failures: readonly string[], file: string): string {
  return [
    `\`${header}\``,
    "",
    ...(failures.length > 0 ? ["First failing rows:", ...failures.map((f) => `- ${f}`), ""] : []),
    `volley bug saved the full report beside you: paste the contents of ${file} below`,
  ].join("\n");
}

/**
 * The new-issue page on the bug form, title and fields filled, at most `url_max` characters
 * (GitHub answers 414 well before a browser minds): failing rows dropped first, then the
 * message and the header shortened; the paste instruction always stays.
 */
export function newIssueUrl(o: {
  title: string;
  message: string;
  header: string;
  failures: readonly string[];
  file: string;
}): string {
  const build = (title: string, message: string, header: string, failures: readonly string[]) => {
    const q = new URLSearchParams({
      template: FORM.template,
      title,
      labels: "bug",
      [FORM.whatHappened]: message,
      [FORM.report]: summaryBody(header, failures, o.file),
    });
    return `https://github.com/${BUG_REPO}/issues/new?${q.toString()}`;
  };
  const max = BUG_DEFAULTS.url_max;
  let failures = o.failures.slice(0, 10);
  let url = build(o.title, o.message, o.header, failures);
  while (url.length > max && failures.length > 0) {
    failures = failures.slice(0, -1);
    url = build(o.title, o.message, o.header, failures);
  }
  const cut = (s: string, n: number) => (s.length > n ? `${s.slice(0, n)}…` : s);
  for (const n of [1000, 300, 100, 0]) {
    if (url.length <= max) break;
    url = build(
      cut(o.title, Math.max(n, 40)),
      cut(o.message, n),
      cut(o.header, Math.max(n, 200)),
      [],
    );
  }
  return url;
}
