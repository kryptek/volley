import { chmodSync, existsSync, readFileSync, renameSync, statSync, writeFileSync } from "node:fs";

/**
 * The broker config Volley's auth needs (mosquitto >= 2.1 + Dynamic Security), the installs it
 * knows, and the config traps it refuses. `volley auth init` / `migrate` write it; the shipped
 * examples/mosquitto-localhost.conf and examples/mosquitto-auth/mosquitto-dynsec.conf are its
 * output for the Apple Silicon Homebrew and container layouts (a test keeps them equal).
 */

export type LayoutName = "brew-arm64" | "brew-intel" | "snap" | "etc" | "container";

export interface Layout {
  name: LayoutName;
  /** The mosquitto.conf the broker reads. */
  config: string;
  /** Where `volley auth` keeps admin.json, accounts.json and tokens.json. */
  authDir: string;
  /** mosquitto_dynamic_security.so */
  plugin: string;
  /** The plugin's state file (it rewrites it on every change). */
  stateFile: string;
  persistence: string;
  /** Interface the listeners bind to ("" = every interface, for a container's port mapping). */
  bind: string;
  log: "stderr" | "stdout";
  /** The command that restarts this broker (printed, or run by `--restart`). */
  restart: string;
  /** `mosquitto_ctrl` as this install names it. */
  ctrl: string;
}

const brew = (prefix: string, name: LayoutName): Layout => ({
  name,
  config: `${prefix}/etc/mosquitto/mosquitto.conf`,
  authDir: `${prefix}/etc/mosquitto/volley`,
  plugin: `${prefix}/opt/mosquitto/lib/mosquitto_dynamic_security.so`,
  stateFile: `${prefix}/var/mosquitto/dynamic-security.json`,
  persistence: `${prefix}/var/mosquitto/`,
  bind: "127.0.0.1",
  log: "stderr",
  restart: "brew services restart mosquitto",
  ctrl: "mosquitto_ctrl",
});

const debianArch = (arch: string) => (arch === "arm64" ? "aarch64-linux-gnu" : "x86_64-linux-gnu");

const snap = (arch: string): Layout => ({
  name: "snap",
  config: "/var/snap/mosquitto/common/mosquitto.conf",
  authDir: "/var/snap/mosquitto/common/volley",
  plugin: `/snap/mosquitto/current/usr/lib/${debianArch(arch)}/mosquitto_dynamic_security.so`,
  // Snap confinement: the broker may write only under $SNAP_COMMON.
  stateFile: "/var/snap/mosquitto/common/dynamic-security.json",
  persistence: "/var/snap/mosquitto/common/",
  bind: "127.0.0.1",
  log: "stderr",
  restart: "sudo snap restart mosquitto",
  ctrl: "mosquitto.ctrl",
});

const etc = (arch: string): Layout => ({
  name: "etc",
  config: "/etc/mosquitto/mosquitto.conf",
  authDir: "/etc/mosquitto/volley",
  plugin: `/usr/lib/${debianArch(arch)}/mosquitto_dynamic_security.so`,
  stateFile: "/var/lib/mosquitto/dynamic-security.json",
  persistence: "/var/lib/mosquitto/",
  bind: "127.0.0.1",
  log: "stderr",
  restart: "sudo systemctl restart mosquitto",
  ctrl: "mosquitto_ctrl",
});

export const LAYOUTS: Record<LayoutName, Layout> = {
  "brew-arm64": brew("/opt/homebrew", "brew-arm64"),
  "brew-intel": brew("/usr/local", "brew-intel"),
  snap: snap(process.arch),
  etc: etc(process.arch),
  container: {
    name: "container",
    config: "/mosquitto/config/mosquitto.conf",
    authDir: "/mosquitto/config/volley",
    plugin: "/usr/lib/mosquitto_dynamic_security.so",
    stateFile: "/mosquitto/data/dynamic-security.json",
    persistence: "/mosquitto/data/",
    bind: "",
    log: "stdout",
    restart: "docker restart <container>",
    ctrl: "mosquitto_ctrl",
  },
};

/**
 * This machine's install: the snap first (the distribution package on Linux may still be 2.0),
 * then Homebrew on Apple Silicon and Intel, else /etc/mosquitto.
 */
export function detectLayout(
  probe: { exists: (path: string) => boolean; arch: string } = {
    exists: existsSync,
    arch: process.arch,
  },
): Layout {
  if (probe.exists("/snap/mosquitto/current")) return snap(probe.arch);
  if (probe.exists("/opt/homebrew/etc/mosquitto")) return LAYOUTS["brew-arm64"];
  if (probe.exists("/usr/local/etc/mosquitto")) return LAYOUTS["brew-intel"];
  return etc(probe.arch);
}

/** Raised from mosquitto's default of 1000, which the Desk's subscriber overflowed under churn. */
export const MAX_QUEUED_MESSAGES = 10_000;

/** The broker config for `layout`. */
export function generateConfig(layout: Layout): string {
  const at = (port: number) => (layout.bind === "" ? `${port}` : `${port} ${layout.bind}`);
  return `# mosquitto config for Volley (generated by \`volley auth init\`; layout: ${layout.name}).
#
# Needs mosquitto >= 2.1: broker auth runs on the Dynamic Security plugin with shared roles
# whose ACLs use %u, which 2.0 does not substitute. Both listeners authenticate every client
# (any local process can reach 1883, and any web page you visit can open a WebSocket to 9001
# and steer your agents) and enforce the roles in examples/mosquitto-auth/. Exposing the broker
# beyond this machine additionally needs TLS (mqtts:// / wss://). See:
#   https://mosquitto.org/documentation/dynamic-security/
#   https://mosquitto.org/man/mosquitto-conf-5.html
#
# Logins are created and deleted at runtime over $CONTROL/dynamic-security/v1 (\`volley auth\`,
# volleyd): no password file, no ACL file, no reload signal. The plugin rewrites its state file
# after every change, so its size drives the cost of a change; volleyd's sweep keeps it to live
# agents plus the fixed identities.

# Global security settings: one plugin for both listeners. Keep this false. With true, the
# plugin options below would sit before the first listener and mosquitto would add an implicit
# listener on port 1883; repeating the plugin per listener instead is refused by 2.1 ("can
# currently only be loaded once").
per_listener_settings false

# The plugin and the state file it owns, BEFORE any listener. \`volley auth init\` creates the
# file with \`${layout.ctrl} dynsec init\` (its admin login is in ${layout.authDir}/admin.json).
plugin ${layout.plugin}
plugin_opt_config_file ${layout.stateFile}

allow_anonymous false

# Disable Nagle on client sockets: with mosquitto's default every control request/response
# round trip took about 41 ms.
set_tcp_nodelay true

# Messages queued per client (QoS 1/2 in flight or offline). The Desk subscribes to the whole
# tree; under spawn churn mosquitto's default of 1000 overflowed it.
max_queued_messages ${MAX_QUEUED_MESSAGES}

# 1. TCP: volley-mcp, the CLI, volleyd, the hooks and any native MQTT client.
listener ${at(1883)}

# 2. WebSocket: the browser clients (volley dash, the Desk). Same plugin and roles.
listener ${at(9001)}
protocol websockets

# Persistence keeps retained registry entries, statuses and the QoS 1 mailbox messages queued
# for offline agents across a broker restart. mosquitto writes it every autosave_interval seconds
# (default 1800); save every 30 s instead (a time, not a change count).
persistence true
persistence_location ${layout.persistence}
autosave_interval 30
autosave_on_changes false

log_dest ${layout.log}
log_type error
log_type warning
log_type notice
log_type information
`;
}

const directives = (text: string) =>
  text
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l !== "" && !l.startsWith("#"));

/**
 * The settings in an existing config that break Dynamic Security, each named with why. `included`
 * are the files of its `include_dir`, which mosquitto reads as part of it.
 */
export function configTraps(text: string, included: readonly string[] = []): string[] {
  const all = [text, ...included].flatMap(directives);
  const traps: string[] = [];
  if (all.some((l) => /^per_listener_settings\s+true$/.test(l))) {
    traps.push(
      "per_listener_settings true: the plugin options before the first listener create an implicit listener on port 1883, and mosquitto 2.1 refuses the plugin repeated per listener; Volley needs per_listener_settings false",
    );
  }
  const plugins = all.filter(
    (l) => /^(plugin|auth_plugin)\s/.test(l) && l.includes("dynamic_security"),
  );
  if (plugins.length > 1) {
    traps.push(
      `the Dynamic Security plugin is loaded twice (${plugins.length} plugin lines): mosquitto 2.1 refuses to start ("can currently only be loaded once")`,
    );
  }
  return traps;
}

/** `<path>.volley-backup-<UTC timestamp>` */
export const backupPath = (path: string, now: Date) =>
  `${path}.volley-backup-${now
    .toISOString()
    .replace(/[-:]/g, "")
    .replace(/\.\d+Z$/, "Z")}`;

/**
 * Write `text` to `path` atomically (temp file + rename, mode kept), backing an existing,
 * different file up first. Unchanged content writes nothing.
 */
export function writeConfig(
  path: string,
  text: string,
  now: Date,
): { written: boolean; backup: string | null } {
  const exists = existsSync(path);
  if (exists && readFileSync(path, "utf-8") === text) return { written: false, backup: null };
  let backup: string | null = null;
  const mode = exists ? statSync(path).mode & 0o777 : 0o644;
  if (exists) {
    backup = backupPath(path, now);
    writeFileSync(backup, readFileSync(path), { mode });
  }
  const tmp = `${path}.tmp`;
  writeFileSync(tmp, text, { mode });
  chmodSync(tmp, mode);
  renameSync(tmp, path);
  return { written: true, backup };
}
