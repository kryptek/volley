import { describe, expect, it } from "vitest";
import { parseDocument } from "yaml";
import type { IssueFacts } from "../src/issue";
import { type AddInput, checkAdd, planAdd } from "../src/wave-add";
import { parseWaveFile } from "../src/wave-file";

const HEAD = `# Generated by volley-issues scripts/wave-from-issues.ts from 4 issue(s).
# plan: cluster A: B10 bundles #590, #591; B11 chained after B10
wave: "w"
repo: "/path/to/repo"
release_branch: "release/w"
model: "claude-opus-5-5"
pipeline: [implement, [spec_review, quality_review], fixup, merge_ready]
merge: "auto"
tasks:
`;
const TASKS = `  B10:
    issue: 590
    issues: [590,591]
    title: "B10: bundle"
    files: ["src/a.ts"]
    footprint: {"confidence":"listed"}
  B11:
    issue: 592
    title: "B11: next"
    after: [B10]  # chained by the planner: shares src/a.ts
    files: ["src/a.ts"]
    footprint: {"confidence":"listed"}
  B12: { issue: 593, title: "B12: flow" }
`;
const TEXT = `${HEAD}${TASKS}`;
const TREE = { "src/a.ts": 4000, "src/new.ts": 900, "README.md": 10 };

const issue = (number: number, title: string, body: string, extra: Partial<IssueFacts> = {}) => ({
  number,
  title,
  body,
  url: `https://github.com/o/r/issues/${number}`,
  state: "OPEN",
  labels: [],
  ...extra,
});
const B13 = issue(602, "B13: fix the thing", "Depends on: #590\n\n## Files\n\n- `src/new.ts`\n");

const input = (over: Partial<AddInput> = {}): AddInput => ({
  text: TEXT,
  wave: "w",
  issues: [B13],
  facts: new Map(),
  after: [],
  tree: TREE,
  slug: "o/r",
  ...over,
});

/** The plan, which must not be a refusal. */
const ok = (over: Partial<AddInput> = {}) => {
  const r = planAdd(input(over));
  if (!("text" in r)) throw new Error(`expected a plan, got ${JSON.stringify(r)}`);
  return r;
};

describe("planAdd", () => {
  it("derives the task as wave-from-issues does and adds only its block", () => {
    const r = ok();
    expect(r.added).toEqual([
      { id: "B13", issue: 602, title: "B13: fix the thing", after: ["B10"] },
    ]);
    const wave = parseWaveFile(r.text);
    expect(wave.task_order).toEqual(["B10", "B11", "B12", "B13"]);
    expect(wave.tasks.B13).toMatchObject({
      issue: 602,
      title: "B13: fix the thing",
      after: ["B10"],
      files: ["src/new.ts"],
      footprint: { confidence: "listed" },
    });
    // Every existing byte is kept: the text is the old one with one block appended to tasks:.
    expect(r.text.startsWith(TEXT)).toBe(true);
    expect(r.text.slice(TEXT.length)).toBe(
      '  B13:\n    issue: 602\n    title: "B13: fix the thing"\n    after: [B10]\n    files: ["src/new.ts"]\n    footprint: {"confidence":"listed"}\n',
    );
    // after: and files: are flow sequences.
    const doc = parseDocument(r.text);
    expect((doc.getIn(["tasks", "B13", "after"], true) as { flow?: boolean }).flow).toBe(true);
    expect((doc.getIn(["tasks", "B13", "files"], true) as { flow?: boolean }).flow).toBe(true);
    expect(r.notes).toEqual([]);
    expect(r.warnings).toEqual([]);
  });

  it("inserts inside tasks: when another key follows it", () => {
    const text = `${TEXT}config: { worktree_root: /path/to/worktrees }\n`;
    const r = ok({ text });
    const at = text.indexOf("config:");
    expect(r.text.slice(0, at)).toBe(text.slice(0, at));
    expect(r.text.endsWith("config: { worktree_root: /path/to/worktrees }\n")).toBe(true);
    expect(parseWaveFile(r.text).tasks.B13?.after).toEqual(["B10"]);
  });

  it("a tasks: map indented by 4 spaces gets its block at the same indent", () => {
    const text = `${HEAD}    T1:\n        issue: 42\n        title: "T1: x"\nconfig: { worktree_root: /path/to/worktrees }\n`;
    const r = ok({ text, issues: [issue(602, "B13: x", "Depends on: none")] });
    const at = text.indexOf("config:");
    expect(r.text.slice(0, at)).toBe(text.slice(0, at));
    expect(r.text.slice(at).startsWith("    B13:\n        issue: 602\n")).toBe(true);
    expect(parseWaveFile(r.text).tasks.B13?.issue).toBe(602);
  });

  it("a file without a final newline gets one before the block", () => {
    const r = ok({ text: TEXT.trimEnd() });
    expect(r.text.startsWith(`${TEXT.trimEnd()}\n  B13:\n`)).toBe(true);
    parseWaveFile(r.text);
  });

  it("--after adds to the body's dependencies, deduplicated", () => {
    expect(ok({ after: ["B12", "B10"] }).added[0]?.after).toEqual(["B10", "B12"]);
  });

  it("an --after that is no task of the wave is a usage refusal listing the wave's ids", () => {
    const r = planAdd(input({ after: ["B99"] }));
    expect(r).toEqual({
      refused: "--after B99: no such task in wave w (its tasks: B10, B11, B12)",
      usage: true,
    });
  });

  it("two issues of one call that depend on each other are added together", () => {
    const a = issue(610, "C1: first", "Depends on: none");
    const b = issue(611, "C2: second", "Depends on: #610, #592");
    const r = ok({ issues: [a, b] });
    expect(r.added).toEqual([
      { id: "C1", issue: 610, title: "C1: first", after: [] },
      { id: "C2", issue: 611, title: "C2: second", after: ["C1", "B11"] },
    ]);
    expect(parseWaveFile(r.text).tasks.C2?.after).toEqual(["C1", "B11"]);
  });

  it("an issue already a task's issue: or a bundle member is refused, naming the task", () => {
    expect(planAdd(input({ issues: [issue(592, "x", "")] }))).toEqual({
      refused: "#592 is already in wave w as B11",
    });
    expect(planAdd(input({ issues: [issue(591, "x", "")] }))).toEqual({
      refused: "#591 is already in wave w as B10",
    });
  });

  it("a closed issue is refused", () => {
    expect(planAdd(input({ issues: [{ ...B13, state: "CLOSED" }] }))).toEqual({
      refused: "#602 is closed; reopen it or pick another issue",
    });
  });

  describe("a dependency outside the wave", () => {
    const dep = issue(
      602,
      "B13: fix the thing",
      "Depends on: #590, #580\n\n## Files\n\n- `src/new.ts`\n",
    );

    it("asks for its facts first", () => {
      expect(planAdd(input({ issues: [dep] }))).toEqual({ need: [580] });
    });

    it("closed → satisfied, dropped", () => {
      const facts = new Map([[580, issue(580, "old", "", { state: "CLOSED" })]]);
      const r = ok({ issues: [dep], facts });
      expect(r.added[0]?.after).toEqual(["B10"]);
      expect(r.notes).toEqual(["#580 is closed: #602's dependency on it is satisfied"]);
    });

    it("labelled merged-to-release → satisfied, dropped", () => {
      const facts = new Map([[580, issue(580, "old", "", { labels: ["merged-to-release"] })]]);
      const r = ok({ issues: [dep], facts });
      expect(r.added[0]?.after).toEqual(["B10"]);
      expect(r.notes).toEqual([
        "#580 is merged to the release: #602's dependency on it is satisfied",
      ]);
    });

    it("open → refused with the way out", () => {
      const facts = new Map([[580, issue(580, "old", "")]]);
      expect(planAdd(input({ issues: [dep], facts }))).toEqual({
        refused:
          "#602 depends on #580, which is not in wave w and is open: add it too (volleyd add w 580 602) or close it first",
      });
    });
  });

  it("an issue with no Depends on: line is added with no deps, and a note", () => {
    const r = ok({ issues: [issue(602, "B13: x", "no deps here")] });
    expect(r.added[0]?.after).toEqual([]);
    expect(r.notes).toEqual([
      "no Depends on:/deps: line in #602; it starts as soon as it is admitted",
    ]);
    expect(r.text.slice(TEXT.length)).not.toContain("    after:");
  });

  it("a tag equal to an existing id falls back to i<N> with the warning", () => {
    const r = ok({ issues: [issue(602, "B12: same tag", "Depends on: none")] });
    expect(r.added[0]?.id).toBe("i602");
    expect(r.warnings[0]).toMatch(/title tag 'B12' would name more than one task/);
    expect(parseWaveFile(r.text).tasks.i602?.issue).toBe(602);
  });

  it("an unreadable dependency line is refused, naming the issue", () => {
    const r = planAdd(input({ issues: [issue(602, "B13: x", "Depends on: B10")] }));
    expect(r).toMatchObject({ refused: expect.stringMatching(/^#602: unparseable dependency/) });
  });

  it("no tree: the footprint is none, its entries unresolved", () => {
    const r = ok({ tree: null });
    expect(parseWaveFile(r.text).tasks.B13?.footprint).toEqual({
      confidence: "none",
      unresolved: ["src/new.ts"],
    });
    expect(r.notes).toContain("no tree: footprints unresolved");
  });

  it("a wave whose tasks are all pinned to one machine pins the new one there too", () => {
    const text = `${HEAD}  T1:\n    issue: 42\n    host: "box"\n  T2:\n    issue: 43\n    host: "box"\n`;
    const r = ok({ text, issues: [issue(602, "B13: x", "Depends on: none")] });
    expect(r.text.slice(text.length)).toContain('    host: "box"\n');
    expect(r.notes).toContain("B13 is pinned to box like the wave's other tasks");
  });
});

describe("checkAdd", () => {
  it("refuses before any fetch: an unknown --after, an issue already in the wave", () => {
    expect(checkAdd({ text: TEXT, wave: "w", issues: [602], after: [] })).toBeNull();
    expect(checkAdd({ text: TEXT, wave: "w", issues: [602], after: ["b10"] })).toMatchObject({
      usage: true,
    });
    expect(checkAdd({ text: TEXT, wave: "w", issues: [590], after: [] })).toEqual({
      refused: "#590 is already in wave w as B10",
    });
  });
});
